"""Make relationship keys unique so joins cannot fan out and inflate measures.

For every Ossie relationship whose "to" (one-side) table has a repeated key, keep the FIRST
row per key and record the removed variants in an extra trailing column `Alternate_Records`,
so nothing is silently lost. Writes cleaned CSVs plus a patched Ossie YAML that declares the
new column.

Usage:
    python tools/clean_dimension_keys.py output_models/fabric_sales_ossie.yaml \
        C:/path/Fabric_Ready C:/path/Clean --out-yaml output_models/fabric_sales_clean_ossie.yaml
"""
from __future__ import annotations

import argparse
import csv
import shutil
import sys
from pathlib import Path

import yaml

EXTRA = "Alternate_Records"


def read(path: Path) -> tuple[list[str], list[dict]]:
    with open(path, newline="", encoding="utf-8-sig") as fh:
        rd = csv.DictReader(fh)
        return list(rd.fieldnames or []), list(rd)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("ossie_yaml", type=Path)
    ap.add_argument("src_dir", type=Path)
    ap.add_argument("out_dir", type=Path)
    ap.add_argument("--out-yaml", type=Path, required=True)
    args = ap.parse_args()

    doc = yaml.safe_load(args.ossie_yaml.read_text(encoding="utf-8"))
    flat_input = "semantic_model" not in doc          # keep the shape the input had
    if flat_input:
        doc = {"version": doc.get("version", "0.2.0.dev0"),
               "semantic_model": [{k: v for k, v in doc.items() if k != "version"}]}
    model = doc["semantic_model"][0]
    datasets = {d["name"]: d for d in model["datasets"]}
    keys: dict[str, str] = {}  # dataset -> key column (the one side of a relationship)
    for r in model.get("relationships", []):
        keys.setdefault(r["to"], r["to_columns"][0])

    args.out_dir.mkdir(parents=True, exist_ok=True)
    report = []
    for name in datasets:
        src = next((p for p in args.src_dir.glob("*.csv") if p.stem.lower() == name.lower()), None)
        if src is None:
            raise SystemExit(f"missing CSV for dataset {name}")
        dst = args.out_dir / src.name
        if name not in keys:
            shutil.copyfile(src, dst)
            continue
        header, rows = read(src)
        key = keys[name]
        seen: dict[str, dict] = {}
        alts: dict[str, list[str]] = {}
        for row in rows:
            k = row[key]
            if k not in seen:
                seen[k] = row
            else:
                other = " / ".join(row[c] for c in header if c != key)
                if other not in alts.setdefault(k, []) and other != " / ".join(
                        seen[k][c] for c in header if c != key):
                    alts[k].append(other)
        out_header = header + ([EXTRA] if alts else [])
        with open(dst, "w", newline="", encoding="utf-8-sig") as fh:
            w = csv.DictWriter(fh, fieldnames=out_header)
            w.writeheader()
            for k, row in seen.items():
                row = dict(row)
                if alts:
                    row[EXTRA] = " | ".join(alts.get(k, []))
                w.writerow(row)
        removed = len(rows) - len(seen)
        report.append(f"{src.name}: key `{key}` had {len(rows)} rows / {len(seen)} distinct; "
                      f"removed {removed} repeated rows ({len(alts)} keys had differing variants)")
        if alts:
            datasets[name]["fields"].append({
                "name": EXTRA,
                "expression": {"dialects": [{"dialect": "ANSI_SQL", "expression": EXTRA}]},
                "datatype": "String",
                "description": "Other records that shared this key in the source data "
                               "(kept for audit; collapsed to one row per key).",
            })

    args.out_yaml.parent.mkdir(parents=True, exist_ok=True)
    args.out_yaml.write_text(
        "# yaml-language-server: $schema=../core-spec/ossie-schema.json\n"
        "# Generated by tools/clean_dimension_keys.py (unique dimension keys)\n"
        + yaml.safe_dump({"version": doc["version"], **doc["semantic_model"][0]}   # flat document
                         if flat_input else doc, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print("\n".join(report) or "no duplicate keys found")
    print(f"wrote {args.out_dir} and {args.out_yaml}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
